@pytest.mark.parametrize("outcome", ["success", "exit", "timeout"])
def test_eval_run_requires_success_even_with_passing_artifacts(tmp_path, outcome):
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    claude = bin_dir / "claude"
    claude.write_text(
        """#!/usr/bin/env python3
import json
import os
from pathlib import Path
import shutil
import sys
import time

root = Path.cwd()
shutil.copytree(os.environ["EVAL_SAMPLE"], root / ".sauces", dirs_exist_ok=True)
state = json.loads((root / ".sauces" / "state.json").read_text())
for name in state["generated_files"] + state["changed_files"]:
    path = root / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("// generated by Sauces\\n")
if os.environ["EVAL_OUTCOME"] == "timeout":
    time.sleep(10)
sys.exit(0 if os.environ["EVAL_OUTCOME"] == "success" else 1)
"""
    )
    claude.chmod(0o755)
    env = {
        **os.environ,
        "PATH": f"{bin_dir}{os.pathsep}{os.environ.get('PATH', '')}",
        "EVAL_SAMPLE": str(SAMPLE),
        "EVAL_OUTCOME": outcome,
    }
    r = run_script(
        "eval.py", "--run", "--fixtures", "flutter-bloc", "--results", str(tmp_path / "run"),
        # Only the timeout case needs a short limit; a tight one makes the others flaky under load.
        "--builds-cmd", "true", "--timeout", "2" if outcome == "timeout" else "30", env=env,
    )
    expected = "PASS" if outcome == "success" else "FAIL"
    assert r.returncode == (0 if outcome == "success" else 1), r.stdout + r.stderr
    [row] = rows(r.stdout)
    assert row.rstrip().endswith(f"{expected} |"), row
    message = {"success": "cook exited 0", "exit": "cook exited 1",
               "timeout": "cook did not finish"}[outcome]
    assert message in r.stderr


